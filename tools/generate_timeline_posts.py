def timestamp(day: str, slug: str) -> str:
    digest = hashlib.sha256(slug.encode("utf-8")).digest()
    hour = 8 + digest[0] % 15
    minute = digest[1] % 60
    second = digest[2] % 60
    return f"{day} {hour:02d}:{minute:02d}:{second:02d}"


def yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def wrap_title(title: str, limit: int = 40) -> list[str]:
    lines: list[str] = []
    current = ""
    width = 0
    for char in title:
        char_width = 1 if ord(char) < 128 else 2
        if current and width + char_width > limit:
            lines.append(current)
            current = char
            width = char_width
        else:
            current += char
            width += char_width
    if current:
        lines.append(current)
    return lines[:2]


