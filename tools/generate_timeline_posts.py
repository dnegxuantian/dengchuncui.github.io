def render_body(article: dict[str, object], cover: str) -> str:
    digest = hashlib.sha256(str(article["slug"]).encode("utf-8")).digest()
    first_heading, second_heading = TEMPLATES[digest[4] % len(TEMPLATES)]
    points = tuple(str(point) for point in article["points"])
    reference_label, reference_url = REFERENCES[str(article["reference"])]
    variants = (
        f"## {first_heading}\n\n{points[0]}\n\n## {second_heading}\n\n- {points[1]}\n- {points[2]}",
        f"## {first_heading}\n\n{points[0]}\n\n{points[1]}\n\n## {second_heading}\n\n{points[2]}",
        f"## {first_heading}\n\n> {points[0]}\n\n- {points[1]}\n- {points[2]}\n\n## {second_heading}",
        f"## {first_heading}\n\n1. {points[0]}\n2. {points[1]}\n3. {points[2]}\n\n## {second_heading}",
        f"## {first_heading}\n\n- {points[0]}\n- {points[1]}\n- {points[2]}\n\n## {second_heading}",
        f"## {first_heading}\n\n{points[0]}\n\n### 实施时\n\n- {points[1]}\n- {points[2]}\n\n## {second_heading}",
    )
    middle = variants[digest[5] % len(variants)]
    return (
        f"{MARKER}\n\n{article['lead']}\n\n"
        f"![{article['title']}]({cover})\n\n"
        f"{middle}\n\n{article['closing']}\n\n"
        f"### 延伸资料\n\n- [{reference_label}]({reference_url})\n"
    )


def render_post(article: dict[str, object]) -> str:
    day = str(article["day"])
    slug = str(article["slug"])
    ts = timestamp(day, slug)
    cover = f"/images/timeline/{slug}.svg"
    description = re.sub(r"\s+", " ", f"{article['lead']} {article['closing']}").strip()[:180]
    tags = "\n".join(f"- {yaml_string(str(tag))}" for tag in article["tags"])
    frontmatter = (
        "---\n"
        f"title: {yaml_string(str(article['title']))}\n"
        f"date: {yaml_string(ts)}\n"
        f"updated: {yaml_string(ts)}\n"
        "categories:\n"
        f"- {yaml_string(str(article['category']))}\n"
        "tags:\n"
        f"{tags}\n"
        f"description: {yaml_string(description)}\n"
        f"cover: {cover}\n"
        f"top_img: {cover}\n"
        f"permalink: /{day[:4]}/{day[5:7]}/{day[8:10]}/{slug}/\n"
        "comments: false\n"
        "---\n\n"
    )
    return frontmatter + render_body(article, cover)


def validate_articles() -> None:
    if len(ARTICLES) != 90:
        raise ValueError(f"Expected 90 timeline articles, got {len(ARTICLES)}")
    slugs: set[str] = set()
    days: set[str] = set()
    month_counts: dict[str, int] = {}
    for article in ARTICLES:
        slug = str(article["slug"])
        day = str(article["day"])
        if slug in slugs or day in days:
            raise ValueError(f"Duplicate slug or day: {slug} / {day}")
        slugs.add(slug)
        days.add(day)
        month = day[:7]
        month_counts[month] = month_counts.get(month, 0) + 1
        text = " ".join(str(article[key]) for key in ("title", "lead", "points", "closing"))
        for phrase in BANNED:
            if phrase in text:
                raise ValueError(f"Banned phrase {phrase!r} in {slug}")
        if str(article["reference"]) not in REFERENCES:
            raise ValueError(f"Unknown reference for {slug}")
    if any(count not in {1, 2} for count in month_counts.values()):
        raise ValueError(f"Unexpected monthly cadence: {month_counts}")


def main() -> None:
    validate_articles()
    POST_DIR.mkdir(parents=True, exist_ok=True)
    IMAGE_DIR.mkdir(parents=True, exist_ok=True)
    expected_posts: set[Path] = set()
    expected_images: set[Path] = set()
    for article in ARTICLES:
        day = str(article["day"])
        slug = str(article["slug"])
        post_path = POST_DIR / f"{day}-{slug}.md"
        image_path = IMAGE_DIR / f"{slug}.svg"
        post_path.write_text(render_post(article), encoding="utf-8")
        image_path.write_text(render_svg(article), encoding="utf-8")
        expected_posts.add(post_path)
        expected_images.add(image_path)

    for post_path in POST_DIR.glob("*.md"):
        if post_path not in expected_posts and MARKER in post_path.read_text(encoding="utf-8"):
            post_path.unlink()
    for image_path in IMAGE_DIR.glob("*.svg"):
        if image_path not in expected_images:
            image_path.unlink()

    month_counts: dict[str, int] = {}
    for article in ARTICLES:
        month = str(article["day"])[:7]
        month_counts[month] = month_counts.get(month, 0) + 1
    double_months = sum(1 for count in month_counts.values() if count == 2)
    print(f"Generated articles: {len(ARTICLES)}")
    print(f"Covered empty months: {len(month_counts)}")
    print(f"Months with two posts: {double_months}")
    print(f"Generated SVGs: {len(expected_images)}")


if __name__ == "__main__":
    main()
